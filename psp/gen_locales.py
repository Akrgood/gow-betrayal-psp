#!/usr/bin/env python3
"""Emit UTF-16 PSP localization tables from the editable paired translations."""
import json
from pathlib import Path
import sys

CONTROL_LANGUAGES = ("English", "French", "Spanish", "German", "Italian", "Portuguese")
CONTROL_IDS = (114, 124, 137, 178, 180, 181, 183, 188, 213, 214, 217, 218, 219, 220, 255)


def read_strings(path):
    rows = {}
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        key, ru, uk = line.split("|")
        index = int(key)
        if index in rows or not 0 <= index < 293 or not ru or not uk:
            raise ValueError(f"{path}:{n}: invalid localization entry")
        rows[index] = (ru.replace(r"\n", "\n"), uk.replace(r"\n", "\n"))
    return rows


def read_controls(path):
    languages = {}
    current = None
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            name = line[1:-1]
            if name not in CONTROL_LANGUAGES or name in languages:
                raise ValueError(f"{path}:{n}: invalid language section")
            current = languages[name] = {}
            continue
        key, text = line.split("|", 1)
        index = int(key)
        if current is None or index not in CONTROL_IDS or index in current or not text:
            raise ValueError(f"{path}:{n}: invalid control string")
        current[index] = text.replace(r"\n", "\n")
    for language in CONTROL_LANGUAGES:
        if set(languages.get(language, {})) != set(CONTROL_IDS):
            raise ValueError(f"{path}: incomplete control strings for {language}")
    return languages


def literal(value):
    return "u" + json.dumps(value, ensure_ascii=False) if value is not None else "nullptr"


if __name__ == "__main__":
    source, controls, target = map(Path, sys.argv[1:])
    rows = read_strings(source)
    control_rows = read_controls(controls)
    result = ["// Generated by gen_locales.py from locales.tsv and controls_psp.tsv.\n"]
    for lang, column in (("Russian", 0), ("Ukrainian", 1)):
        result.append(f"static constexpr const char16_t* k{lang}[293] = {{\n")
        for index in range(293):
            result.append(f"  {literal(rows[index][column] if index in rows else None)},  // {index}\n")
        result.append("};\n")
    result.append("static constexpr int kControlIds[] = {" + ", ".join(map(str, CONTROL_IDS)) + "};\n")
    for language in CONTROL_LANGUAGES:
        result.append(f"static constexpr const char16_t* k{language}Controls[] = {{\n")
        for index in CONTROL_IDS:
            result.append(f"  {literal(control_rows[language][index])},  // {index}\n")
        result.append("};\n")
    target.write_text("".join(result), encoding="utf-8")
